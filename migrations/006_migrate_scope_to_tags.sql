-- ═══════════════════════════════════════════════════════════════════
-- 정리 작업 2-A — scope='all' 인 기존 일정에 tags=['전체'] 자동 추가
-- ═══════════════════════════════════════════════════════════════════
-- 배경:
--   기존에는 scope='all' | 'personal' 로 공개 범위를 표현했으나,
--   tags 기반으로 단순화. 새 규칙:
--     tags=['전체', ...]  → 공유 일정 (대시보드/나의 할 일 매칭)
--     tags=[] (빈 배열)   → 개인 일정 (본인만 보임)
--
-- scope='all' 이었던 기존 일정은 사용자 의도상 '전체 공유' 였으므로
-- tags=['전체'] 로 자동 변환. scope='personal' 인 일정은 그대로 두면
-- tags 가 NULL/[] 이므로 자연스럽게 개인 일정으로 처리됨.
--
-- 영향:
--   기존 events 중 scope='all' AND tags 가 비어있거나 NULL 인 행 →
--     tags=['전체'] 로 채워짐.
--   이미 tags 가 채워진 행은 보존 (예: 이미 ['전체','담임'] 인 경우 그대로).
--
-- scope 컬럼 자체는 DROP 하지 않음 (데이터 보존, 향후 사용 안 함).
-- 코드에서는 scope 를 더 이상 읽거나 쓰지 않음.
-- ═══════════════════════════════════════════════════════════════════

UPDATE events
SET tags = ARRAY['전체']
WHERE scope = 'all'
  AND (tags IS NULL OR tags = '{}');
