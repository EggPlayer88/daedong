    await page.evaluate(() => { window.root.unmount(); window.mount() })
    await button('같은 관계 변경 요청으로 결과 확인').waitFor()
    assert.equal(await back().isDisabled(), true)
    await button('같은 관계 변경 요청으로 결과 확인').click()
