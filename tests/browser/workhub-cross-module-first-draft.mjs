import assert from 'node:assert/strict'

export async function checkFirstDraftSentence({ page, test, request, noSideEffects }) {
  const button = name => page.getByRole('button', { name, exact: true })
  const region = name => page.getByRole('region', { name, exact: true })
  const form = name => page.getByRole('form', { name, exact: true })
  const box = () => page.getByRole('textbox', { name: '질문 또는 부탁할 일', exact: true })
  const results = () => region('교사 검색 결과')
  const candidate = name => results().getByRole('button', { name })
  const goForm = async label => { await button('작성 화면에서 확인').click(); await button(label).click() }
  async function reply(text) { await box().fill(text); await button('초안 정보 이어 입력').click() }
  const tomorrow = async () => page.evaluate(() => new Date(Date.parse(window.cross.basisDate + 'T00:00:00Z') + 86400000).toISOString().slice(0,10))

  await test('첫 메시지 문장의 이름을 한 번만 말하고 동명이인을 직접 고른 뒤 여러 줄 본문을 확인한다', async () => {
    await page.evaluate(() => {window.cross.namesake=true;window.cross.budgetExhausted=true})
    const body='내일까지 자료 확인 부탁드립니다.\n김서진에게 보낼 자료도 확인해 주세요.'
    await request('이민준 선생님에게 “'+body+'”라는 메시지 초안 만들어줘', '메시지 초안 확인')
    await results().waitFor()
    assert.equal(await candidate(/이민준.*선택/).count(),2)
    assert.match(await region('작성 중인 메시지').innerText(), /받는 사람 · 0명/)
    assert.equal(await button('작성 화면에서 확인').isDisabled(),true)
    await noSideEffects()
    await candidate(/이민준.*연구부.*선택/).click()
    await goForm('전달받은 메시지 초안 사용')
    const editor=form('새 메시지 작성')
    assert.equal(await editor.getByLabel('메시지',{exact:true}).inputValue(),body)
    assert.equal(await editor.getByRole('checkbox',{checked:true}).count(),1)
    assert.equal(await editor.getByRole('checkbox',{name:/이민준.*연구부.*gaon-minjun-alt/}).isChecked(),true)
    await noSideEffects()
  })
  await test('수합 한 문장으로 기한·제목·안내와 두 교사 후보를 읽고 선택한 두 ID만 전달한다', async () => {
    const date = await tomorrow()
    await request('내일까지 이민준 선생님과 김서진 선생님에게 “체험학습 계획서” 안내는 “줄바꿈도\n보존합니다.” 수합 초안 만들어줘','수합 초안 확인')
    const card=region('작성 중인 수합')
    await card.getByText(date,{exact:true}).waitFor()
    await candidate(/이민준.*선택/).click()
    await candidate(/김서진.*선택/).waitFor()
    assert.equal(await button('작성 화면에서 확인').isDisabled(),true)
    await candidate(/김서진.*선택/).click()
    assert.match(await card.innerText(), /제출 대상 · 2명/)
    assert.doesNotMatch(await card.innerText(), /제출 기한은 언제|누가 제출/)
    await goForm('수합 초안 사용')
    const editor=form('수합 초안 작성')
    assert.equal(await editor.getByLabel('수합 제목',{exact:true}).inputValue(),'체험학습 계획서')
    assert.equal(await editor.getByLabel('안내 내용',{exact:true}).inputValue(),'줄바꿈도\n보존합니다.')
    assert.equal(await editor.getByLabel('제출 기한',{exact:true}).inputValue(),date)
    assert.equal(await editor.getByLabel('책임 교사 1',{exact:true}).inputValue(),'gaon-minjun')
    assert.equal(await editor.getByLabel('책임 교사 2',{exact:true}).inputValue(),'gaon-seojin')
    await noSideEffects()
  })
  await test('기한과 교사가 있는 수합은 누락한 제목만 묻고 원래 날짜·선택을 보존한다', async () => {
    const date=await tomorrow()
    await request('김서진 선생님께 내일까지 수합 초안 만들어줘','수합 초안 확인')
    await candidate(/김서진.*선택/).click()
    await page.getByText('수합 제목을 적어 주세요.',{exact:true}).waitFor()
    assert.equal(await button('작성 화면에서 확인').isDisabled(),true)
    await reply('학년별 안내문')
    await goForm('수합 초안 사용')
    const editor=form('수합 초안 작성')
    assert.equal(await editor.getByLabel('수합 제목',{exact:true}).inputValue(),'학년별 안내문')
    assert.equal(await editor.getByLabel('제출 기한',{exact:true}).inputValue(),date)
    assert.equal(await editor.getByLabel('책임 교사 1',{exact:true}).inputValue(),'gaon-seojin')
    await noSideEffects()
  })
  await test('빈 검색·재검색과 후보 건너뛰기 후에도 이미 입력한 수합 제목을 유지하고 불명확한 날짜만 다시 받는다', async () => {
    const date=await tomorrow()
    await request('주말까지 없는교사, 김서진 선생님에게 실험 계획서 수합 초안 만들어줘','수합 초안 확인')
    await results().getByText(/일치하는 교사가 없습니다/).waitFor()
    await button('이 이름 건너뛰기').click()
    await candidate(/김서진.*선택/).click()
    await region('작성 중인 수합').getByText('제출 기한은 언제인가요?',{exact:true}).waitFor()
    await reply('내일')
    await goForm('수합 초안 사용')
    const editor=form('수합 초안 작성')
    assert.equal(await editor.getByLabel('수합 제목',{exact:true}).inputValue(),'실험 계획서')
    assert.equal(await editor.getByLabel('제출 기한',{exact:true}).inputValue(),date)
    assert.equal(await editor.getByLabel('책임 교사 1',{exact:true}).inputValue(),'gaon-seojin')
    await noSideEffects()
  })
  await test('첫 이름 검색이 실패해도 같은 입력으로 복구하고 빠진 본문만 한 번 받는다', async () => {
    await page.evaluate(()=>{window.cross.denyRecipientSearch=true})
    await request('이민준 선생님에게 메시지 초안 만들어줘','메시지 초안 확인')
    await page.getByText(/교사 목록을 확인하지 못했습니다/).waitFor()
    assert.equal(await box().inputValue(),'이민준')
    await page.evaluate(()=>{window.cross.denyRecipientSearch=false})
    await box().fill('')
    await button('이 이름 다시 찾기').click()
    await candidate(/이민준.*선택/).click()
    await page.getByText('메시지 본문을 적어 주세요.',{exact:true}).waitFor()
    const body='안내문입니다.\n내일까지 확인해 주세요.'
    await reply(body)
    await goForm('전달받은 메시지 초안 사용')
    assert.equal(await form('새 메시지 작성').getByLabel('메시지',{exact:true}).inputValue(),body)
    assert.equal(await form('새 메시지 작성').getByRole('checkbox',{checked:true}).count(),1)
    await noSideEffects()
  })
}
