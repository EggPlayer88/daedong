const fs=require('node:fs'),path=require('node:path'),{pathToFileURL}=require('node:url');
const assert=require('node:assert/strict');
const schema=JSON.parse(fs.readFileSync(path.join(__dirname,'schema-contract.json'),'utf8'));
const {chromium}=require(process.env.WORKHUB_PLAYWRIGHT||'playwright');
(async()=>{
 const browser=await chromium.launch({headless:true,channel:'chrome'});
 const page=await browser.newPage({viewport:{width:1440,height:1080}});
 const errors=[],requests=[];
 page.on('pageerror',e=>errors.push(String(e)));page.on('request',r=>requests.push(r.url()));
 await page.goto(pathToFileURL(path.join(__dirname,'overview.html')).href);
 assert.equal(await page.locator('.domain').count(),12);
 assert.equal(await page.locator('.table-pick').count(),schema.counts.total_tables);
 assert.match(await page.locator('#detail h3').innerText(),/accounts/);
 await page.locator('#query').fill('document_inputs');
 assert.equal(await page.locator('.table-pick').count(),1);
 assert.match(await page.locator('#detail').innerText(),/file_scope_key/);
 await page.locator('#query').fill('impossible-table-name');
 assert.equal(await page.locator('.table-pick').count(),0);
 assert.match(await page.locator('#detail').innerText(),/검색 결과가 없습니다/);
 await page.locator('#query').fill('');
 await page.locator('.domain').filter({hasText:'학생·평가·생기부'}).click();
 assert.equal(await page.locator('#domain-filter').inputValue(),'student');
 await page.locator('#flow-tab-4').click();
 assert.match(await page.locator('#flow-rule').innerText(),/A→B→A/);
 await page.locator('#flow-tab-4').press('ArrowRight');
 assert.equal(await page.locator('#flow-tab-5').getAttribute('aria-selected'),'true');
 assert.match(await page.locator('#flow-rule').innerText(),/자동 재호출하지/);
 await page.locator('#domain-filter').selectOption('');
 for(const table of ['messenger_threads','collection_templates','timetable_basis_revisions']){
  await page.locator('#query').fill(table);
  await page.locator('.table-pick').filter({has:page.locator('span').filter({hasText:new RegExp('^'+table+'$')})}).click();
  assert.equal(await page.locator('#detail h3').innerText(),table);
 }
 await page.locator('#query').fill('');
 await page.locator('#flow-tab-1').click();
 assert.match(await page.locator('#flow-rule').innerText(),/파일 생성은 정식 제출이 아닙니다/);
 await page.locator('#flow-tab-2').click();
 assert.match(await page.locator('#flow-rule').innerText(),/상대 수락만으로/);
 await page.locator('#flow-tab-0').click();
 assert.match(await page.locator('#flow-rule').innerText(),/교사 간 메신저와 Claude/);
 await page.evaluate(()=>window.scrollTo(0,0));
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true);
 await page.screenshot({path:path.join(__dirname,'overview-desktop.png')});
 await page.setViewportSize({width:390,height:844});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true);
 await page.screenshot({path:path.join(__dirname,'overview-mobile.png')});
 assert.deepEqual(errors,[]);
 assert.equal(requests.filter(u=>/^https?:/i.test(u)).length,0);
 const result={status:'passed',tables:schema.counts.total_tables,checks:['12개 영역·전체 표 표시','기존·신규 3영역 표 검색·열 명세·빈 결과','영역 선택','6개 업무 흐름·방향키 탭','1440/390 화면 넘침 없음','브라우저 실행 오류 0','외부 통신 0'],not_proven:['실제 DB 또는 API 동작']};
 fs.writeFileSync(path.join(__dirname,'overview-qa.json'),JSON.stringify(result,null,2)+'\n');console.log(JSON.stringify(result));
 await browser.close();
})().catch(e=>{console.error(e);process.exitCode=1;});
